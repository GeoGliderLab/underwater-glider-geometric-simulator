function m = model(p)
%MODEL Construct checked constants. Edit parameters BEFORE calling model.
if nargin == 0, p = glider.parameters(); end
assert(all(isfinite(p.mass)) && all(p.mass>0),'glider:parameters','Invalid masses.');
assert(p.rho>0 && p.volume>0 && p.water.radius>0 && p.water.stroke>0, ...
    'glider:parameters','Invalid fluid or geometry parameters.');
assert(isequal(size(p.limits),[3,2]) && all(p.limits(:,2)>p.limits(:,1)), ...
    'glider:parameters','Invalid joint intervals.');
assert(norm(p.added_mass-p.added_mass','fro')<1e-12 && ...
    min(eig(p.added_mass))>=0,'glider:parameters','Added mass must be symmetric PSD.');
assert(all([p.hydro.drag;p.hydro.induced_drag;p.hydro.lift;p.hydro.side_drag; ...
    p.hydro.rot_linear(:);p.hydro.rot_quadratic(:)]>=0),'glider:parameters','Invalid damping.');
assert(abs(norm(p.hydro.normal)-1)<1e-12 && abs(norm(p.hydro.side)-1)<1e-12, ...
    'glider:parameters','Hydrodynamic directions must be unit vectors.');
assert(ismember(p.water.flux,{'ambient_in_comoving_out','zero'}), ...
    'glider:parameters','Unknown flux closure.');
assert(all(isfinite([p.pump.surface_pressure,p.pump.back_pressure,p.pump.viscous, ...
    p.pump.coulomb,p.pump.speed_scale])) && p.pump.viscous>=0 && ...
    p.pump.coulomb>=0 && p.pump.speed_scale>0,'glider:parameters','Invalid pump parameters.');
assert(norm(p.home(1:3,4,4)-(p.water.tip+[0;0;p.water.stroke]))<1e-12 && ...
    norm(p.home(1:3,1:3,4)-eye(3),'fro')<1e-12 && ...
    norm(p.screw(:,3)-[0;0;0;0;0;-1])<1e-12 && ...
    norm(p.limits(3,:)-[0,p.water.stroke])<1e-12, ...
    'glider:parameters','Water closure requires the documented piston geometry.');
m = p; m.parent = [0,1,2,1]; m.I = zeros(6,6,4);
for i=1:4
    J=p.inertia(:,:,i); e=eig(J);
    assert(norm(J-J','fro')<1e-12 && min(e)>0 && 2*max(e)<=sum(e)+1e-12, ...
        'glider:inertia','COM inertia must satisfy positivity and triangle inequalities.');
    m.I(:,:,i)=glider.spatial_inertia(p.mass(i),p.com(:,i),J);
end
m.version='0.1.0';
end
